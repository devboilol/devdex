package com.youki.dex.server

import java.io.BufferedReader
import java.io.InputStreamReader
import java.io.PrintWriter
import java.net.InetAddress
import java.net.ServerSocket
import java.net.Socket
import java.security.MessageDigest
import java.util.concurrent.Semaphore
import java.util.concurrent.TimeUnit

/**
 * ShellServer — tiny command server launched via `app_process` as root (uid 0)
 * or shell (uid 2000). Listens on 127.0.0.1:7171 only.
 *
 * SECURITY (patched):
 *  - The auth token is NO LONGER broadcast. It used to be sent with an
 *    implicit `am broadcast`, so ANY app registering a receiver for the
 *    action could read it and then run commands as root/shell through this
 *    socket. The token is now generated by the app, stored in the app's
 *    private prefs, and handed to this process through the environment
 *    (YOUKI_SHELL_TOKEN) at launch. If it is missing the server refuses to
 *    start instead of falling back to something guessable.
 *  - Idle sockets time out (a local app could previously open connections
 *    and hold a thread forever without authenticating).
 *  - Concurrent clients are capped.
 *  - Timed-out commands are killed instead of being left running.
 *  - stdout/stderr buffers are thread-safe and size-capped.
 *  - Commands may be sent base64-encoded (CMDB64:) so multi-line scripts
 *    can't break the line-based protocol.
 */
object ShellServer {

    private const val PORT = 7171
    private const val MAGIC = "YOUKI_SHELL_V1"
    private const val ENV_TOKEN = "YOUKI_SHELL_TOKEN"

    private const val MAX_CLIENTS = 4
    private const val IDLE_TIMEOUT_MS = 30_000
    private const val CMD_TIMEOUT_S = 10L
    private const val MAX_OUTPUT_CHARS = 256 * 1024

    private val clientSlots = Semaphore(MAX_CLIENTS)

    @Volatile private var sessionToken: String = ""

    @JvmStatic
    fun main(args: Array<String>) {
        val token = System.getenv(ENV_TOKEN).orEmpty()
        if (token.length < 32) {
            System.err.println("[$MAGIC] ERROR: $ENV_TOKEN missing or too short — refusing to start")
            System.exit(1)
            return
        }
        sessionToken = token

        val uid = getUid()
        println("[$MAGIC] ShellServer starting... uid=$uid")
        if (uid != 0 && uid != 2000) {
            System.err.println("[$MAGIC] ERROR: Must run as root (0) or shell (2000), got uid=$uid")
            System.exit(1)
            return
        }

        try {
            val server = ServerSocket(PORT, 8, InetAddress.getByName("127.0.0.1"))
            println("[$MAGIC] Ready on 127.0.0.1:$PORT")
            while (true) {
                try {
                    val client = server.accept()
                    if (!clientSlots.tryAcquire()) {
                        try { client.close() } catch (ignored: Exception) {}
                        continue
                    }
                    client.soTimeout = IDLE_TIMEOUT_MS
                    Thread {
                        try { handleClient(client) } finally { clientSlots.release() }
                    }.start()
                } catch (e: Exception) {
                    System.err.println("[$MAGIC] Accept error: ${e.message}")
                }
            }
        } catch (e: Exception) {
            System.err.println("[$MAGIC] Fatal: ${e.message}")
            System.exit(1)
        }
    }

    private fun tokenMatches(candidate: String): Boolean =
        MessageDigest.isEqual(
            candidate.toByteArray(Charsets.UTF_8),
            sessionToken.toByteArray(Charsets.UTF_8)
        )

    private fun handleClient(socket: Socket) {
        try {
            val reader = BufferedReader(InputStreamReader(socket.getInputStream()))
            val writer = PrintWriter(socket.getOutputStream(), true)

            writer.println(MAGIC)

            val tokenLine = reader.readLine() ?: return
            if (!tokenLine.startsWith("TOKEN:") || !tokenMatches(tokenLine.removePrefix("TOKEN:"))) {
                writer.println("ERR:Invalid token")
                return
            }
            writer.println("TOKEN_OK")

            while (!socket.isClosed) {
                val line = reader.readLine() ?: break
                when {
                    line == "PING" -> writer.println("PONG")
                    line == "UID" -> writer.println("uid=${getUid()}")
                    line == "EXIT" -> { writer.println("BYE"); break }
                    line.startsWith("CMDB64:") -> {
                        val cmd = try {
                            String(java.util.Base64.getDecoder().decode(line.removePrefix("CMDB64:")), Charsets.UTF_8)
                        } catch (e: Exception) { null }
                        if (cmd == null) writer.println("ERR:Bad encoding")
                        else sendResult(writer, runCommand(cmd))
                    }
                    line.startsWith("CMD:") -> sendResult(writer, runCommand(line.removePrefix("CMD:")))
                    else -> writer.println("ERR:Unknown command")
                }
            }
        } catch (e: Exception) {
            System.err.println("[$MAGIC] Client error: ${e.message}")
        } finally {
            try { socket.close() } catch (ignored: Exception) {}
        }
    }

    private fun sendResult(writer: PrintWriter, result: String) {
        // A line that is exactly the terminator would cut the client's read short.
        val safe = result.lineSequence().joinToString("\n") { if (it == "__DONE__") "__DONE__ " else it }
        writer.println(safe)
        writer.println("__DONE__")
    }

    private fun readBounded(stream: java.io.InputStream, sink: StringBuffer) {
        try {
            val reader = InputStreamReader(stream)
            val buf = CharArray(4096)
            while (true) {
                val n = reader.read(buf)
                if (n < 0) break
                // keep draining after the cap so the child never blocks on a full pipe
                if (sink.length < MAX_OUTPUT_CHARS) sink.append(buf, 0, minOf(n, MAX_OUTPUT_CHARS - sink.length))
            }
        } catch (ignored: Exception) {}
    }

    private fun runCommand(cmd: String): String {
        return try {
            val process = Runtime.getRuntime().exec(arrayOf("sh", "-c", cmd))
            val stdout = StringBuffer()
            val stderr = StringBuffer()
            val outThread = Thread { readBounded(process.inputStream, stdout) }
            val errThread = Thread { readBounded(process.errorStream, stderr) }
            outThread.start()
            errThread.start()

            val finished = process.waitFor(CMD_TIMEOUT_S, TimeUnit.SECONDS)
            if (!finished) process.destroyForcibly()
            outThread.join(2000)
            errThread.join(2000)

            buildString {
                if (stdout.isNotBlank()) append(stdout.toString().trim())
                if (stderr.isNotBlank()) { if (isNotEmpty()) append("\n"); append(stderr.toString().trim()) }
                if (!finished) { if (isNotEmpty()) append("\n"); append("ERROR: timed out after ${CMD_TIMEOUT_S}s (killed)") }
                if (isEmpty()) append("(no output)")
            }
        } catch (e: Exception) { "ERROR: ${e.message}" }
    }

    private fun getUid(): Int = try {
        Runtime.getRuntime().exec(arrayOf("id", "-u"))
            .inputStream.bufferedReader().readText().trim().toInt()
    } catch (e: Exception) { -1 }
}
